// lib/main.dart
import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart'; // Generated by flutterfire configure
import 'screens/splash_screen.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
  } catch (e) {
    debugPrint("Firebase Web Init Bypassed: $e");
  }

  runApp(const CampusBuddyAppRoot());
}

class CampusBuddyAppRoot extends StatefulWidget {
  const CampusBuddyAppRoot({super.key});

  @override
  State<CampusBuddyAppRoot> createState() => _CampusBuddyAppRootState();
}

class _CampusBuddyAppRootState extends State<CampusBuddyAppRoot> {
  bool _dark = true;

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Campus Buddy',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(brightness: Brightness.light, primarySwatch: Colors.blue),
      darkTheme: ThemeData(brightness: Brightness.dark, scaffoldBackgroundColor: const Color(0xFF121212)),
      themeMode: _dark ? ThemeMode.dark : ThemeMode.light,
      home: CampusBuddySplashScreen(
        onToggleTheme: () => setState(() { _dark = !_dark; }),
        isDarkMode: _dark,
      ),
    );
  }
}
